#!/usr/bin/env python3
"""Train YOLOv11, YOLOv12 or RT-DETR from scratch on CCv2.

Uses pseudo-labels generated by RetinaFace as supervision. Expects a
YOLO-style data directory with images/ and labels/ subfolders already
prepared (see prepare_yolo_data.py or follow the paper's protocol).

Usage:
    python 04_train_scratch.py --model yolo11n --epochs 100 --batch 32
    python 04_train_scratch.py --model yolo12n --epochs 100 --batch 16
    python 04_train_scratch.py --model rtdetr-l --epochs 80 --batch 8
"""
import argparse


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--model", required=True,
                   choices=["yolo11n", "yolo12n", "rtdetr-l"])
    p.add_argument("--data", default="yolo_data/data.yaml")
    p.add_argument("--epochs", type=int, default=100)
    p.add_argument("--batch", type=int, default=32)
    p.add_argument("--imgsz", type=int, default=640)
    p.add_argument("--project", default="runs")
    p.add_argument("--name", default=None)
    p.add_argument("--seed", type=int, default=42)
    args = p.parse_args()

    from ultralytics import YOLO

    run_name = args.name or f"{args.model.replace('-', '_')}_scratch"
    cfg = f"{args.model}.yaml"

    if args.model == "rtdetr-l":
        model = YOLO(cfg, task="detect")
        optimizer = "AdamW"
        lr0 = 0.0001
    else:
        model = YOLO(cfg)
        optimizer = "SGD"
        lr0 = 0.01

    model.train(
        data=args.data,
        epochs=args.epochs,
        batch=args.batch,
        imgsz=args.imgsz,
        optimizer=optimizer,
        lr0=lr0,
        cos_lr=True,
        pretrained=False,
        project=args.project,
        name=run_name,
        seed=args.seed,
        device=0,
    )


if __name__ == "__main__":
    main()
